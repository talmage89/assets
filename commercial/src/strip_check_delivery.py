"""Independent raw shipping-map/UV/normal/part budget checks for strip GLBs."""
import argparse,hashlib,json,sys
from pathlib import Path
import numpy as np
HERE=Path(__file__).resolve().parent;sys.path[:0]=[str(HERE.parents[1]),str(HERE)]
from kit.gltf import GLB
from strip_delivery import part_materials


def run(seeds,folder):
    rows=[]
    for seed in seeds:
        path=folder/f'strip-{seed}.glb';raw=GLB(path);doc=raw.json;meta=json.loads(path.with_suffix('.json').read_text());density=[];norm=0;count=0;minimum_uv=1.
        for node_index,node in enumerate(doc['nodes']):
            if 'mesh' not in node:continue
            for pr in doc['meshes'][node['mesh']]['primitives']:
                pos=raw.accessor(pr['attributes']['POSITION']);xf=raw.world(node_index);pos=(np.column_stack((pos,np.ones(len(pos))))@xf.T)[:,:3];ind=raw.accessor(pr['indices']).reshape(-1,3);count+=len(ind)
                n=raw.accessor(pr['attributes']['NORMAL']);norm=max(norm,float(np.max(np.abs(np.linalg.norm(n,axis=1)-1))))
                uv=raw.accessor(pr['attributes']['TEXCOORD_0']);q=uv[ind];e=q[:,1]-q[:,0];f=q[:,2]-q[:,0];area=np.abs(e[:,0]*f[:,1]-e[:,1]*f[:,0])/2
                mat=doc['materials'][pr['material']];name=mat['name']
                # Scalar glass is exempt from image-chart density, though its
                # normals and geometry still enter the independent checks.
                if 'Glass' in name:continue
                assert (area>1e-14).all(),('Degenerate actual image UV',seed,node['name'],name,float(area.min()))
                minimum_uv=min(minimum_uv,float(area.min()))
                pa=pos[ind];worldarea=np.linalg.norm(np.cross(pa[:,1]-pa[:,0],pa[:,2]-pa[:,0]),axis=1)/2
                density.extend(np.sqrt(area/np.maximum(worldarea,1e-20)).tolist())
                if name=='StripTenantInks':assert 'TEXCOORD_1' in pr['attributes'],('Missing emission selection UV',node['name'])
        assert norm<2e-4 and count==meta['total_triangles'];maximum=10 if meta['style']=='mansard' else 9
        assert len(doc['materials'])<=maximum,(seed,len(doc['materials']),maximum)
        assert meta['building_triangles']<=80000 and all(v<=7000 for k,v in meta['triangles'].items() if k.startswith('Bay_'))
        # All image bytes are generated by this worktree or the library; final
        # exports use the exact encoded PNG payload, not a renderer rebake.
        known={hashlib.sha256(p.read_bytes()).hexdigest() for root in (Path('textures/ship'),Path('build/strip/signs-look'),Path('../ground/textures/ship'),Path('../shrubs/textures/ship'),Path('../houses/textures/ship')) for p in root.glob('*.png')}
        hashes=[]
        for im in doc['images']:
            v=doc['bufferViews'][im['bufferView']];start=v.get('byteOffset',0);blob=raw.binary[start:start+v['byteLength']] if hasattr(raw,'binary') else raw.bin[start:start+v['byteLength']]
            digest=hashlib.sha256(blob).hexdigest();assert digest in known,('Altered image bytes',im);hashes.append(digest)
        rows.append(dict(seed=seed,passed=True,triangles=count,building_triangles=meta['building_triangles'],materials=len(doc['materials']),parts=part_materials(doc,meta),maximum_normal_length_error=norm,minimum_uv_triangle_area=minimum_uv,uv_units_per_meter_percentiles=np.percentile(density,[5,50,95]).tolist(),image_sha256=hashes,scope='Raw image charts, normals, source-authored budgets and embedded PNG byte identity. Tiling/shared UV overlap is intentional. Image UV units/m are not one uniform atlas texel density.'))
    (folder/'delivery-check.json').write_text(json.dumps(dict(passed=True,rows=rows),indent=2)+'\n');print('STRIP DELIVERY CHECK',len(rows),'PASS')

if __name__=='__main__':
    a=argparse.ArgumentParser();a.add_argument('--seeds',default='201,202,203,204');a.add_argument('--source-root',type=Path,default=Path('build/strip-look'));a=a.parse_args(sys.argv[sys.argv.index('--')+1:]);run(map(int,a.seeds.split(',')),a.source_root)
