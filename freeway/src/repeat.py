"""Repeat deterministic products; GPU maps use the separate tolerance target.

CPU fields are independently regenerated in isolation. Native context caches
and exported geometry are regenerated by fresh serial Blender processes in
this delivery directory so their repository-relative glTF URIs also compare
byte for byte. Blend containers and stochastic renders are excluded explicitly.
"""
import sys,subprocess,json,hashlib,os,shlex
from pathlib import Path
HERE=Path(__file__).resolve().parent;ASSET=HERE.parent;ROOT=ASSET.parent

def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()
def run(command,cwd,log):
 with log.open('w') as f:subprocess.run(command,cwd=cwd,stdout=f,stderr=subprocess.STDOUT,check=True)

def main():
 target=Path('build/repeat');target.mkdir(parents=True,exist_ok=True)
 fields=target/'fields';fields.mkdir(exist_ok=True);(fields/'build').mkdir(exist_ok=True)
 link=fields/'refs'
 if not link.exists():link.symlink_to(ASSET/'refs',target_is_directory=True)
 products=[]
 for folder in ('textures/source','textures/checkpoint','textures/context'):
  products.extend(sorted(Path(folder).glob('*.png')))
  if folder.endswith('context'):products.extend(sorted(Path(folder).glob('*.json')))
 products += [Path('build')/n for n in ('cameras.json','reference-balance.json','texture-plan.json','context-colors-audit.json')]
 products += sorted(Path('build').glob('balanced-*.jpg'))
 expected={str(p):sha(p) for p in products if p.exists()}
 for name,args in [('graphics',[]),('textures',['--size','4096']),('context_colors',[]),('landscape',[]),('matches',[])]:
  run([sys.executable,str(HERE/(name+'.py')),*args],fields,target/(name+'.log'))
 rows=[]
 for p,h in expected.items():
  q=fields/p;same=q.exists() and sha(q)==h
  assert same,('CPU repeat differs',p)
  rows.append(dict(file=p,bytes=Path(p).stat().st_size,sha256=h,identical=True))
 if '--fields-only' in sys.argv:
  Path('build/repeat-cpu.json').write_text(json.dumps(dict(files=rows,all_identical=True),indent=2))
  print('CPU REPEAT PASSED',len(rows),'independently regenerated files byte-identical');return
 generated=[*sorted(Path('build/context').glob('*.glb'))]
 generated += [p for p in sorted(Path('export').rglob('*')) if p.suffix in ('.gltf','.bin')]
 generated += [Path('build')/n for n in ('modules.json','scene-101.json','scene-202.json','edge-support-101.json','edge-support-202.json')]
 before={str(p):dict(sha256=sha(p),bytes=p.stat().st_size) for p in generated}
 blender=shlex.split(os.environ.get('BLENDER_BINARY','blender'))+['-t','2','-b','--factory-startup','--python-exit-code','1','--python']
 for kind,args in [('native',['--kind','native']),('signal',['--kind','signal']),('utility',['--kind','utility'])]:
  run(blender+[str(HERE/'prepare_context.py'),'--',*args],ASSET,target/(kind+'.log'))
 run(blender+[str(HERE/'apartment_context.py')],ASSET,target/'apartment.log')
 run(blender+[str(HERE/'build.py'),'--','--seeds','101','202','--stage','look','--out','build/Freeway.blend'],ASSET,target/'build.log')
 geometry=[]
 for path,old in before.items():
  same=Path(path).exists() and sha(path)==old['sha256']
  geometry.append(dict(file=path,**old,identical=same))
 report=dict(scope='Exact bytes: independent CPU manufacture/graphics/paint/grass/calibration outputs, fresh native context GLBs, external glTF/BIN and scene/edge manifests. Blend containers and stochastic renders excluded; GPU maps have a separate tolerance comparison.',cpu_files=rows,geometry_files=geometry,all_identical=all(r['identical'] for r in geometry))
 Path('build/repeat.json').write_text(json.dumps(report,indent=2))
 assert report['all_identical'],[r['file'] for r in geometry if not r['identical']]
 presentation=[]
 if Path('build/final-provenance.json').exists() and list(Path('docs').glob('*.jpg')):
  products=[*sorted(Path('docs').glob('*.jpg')),*sorted(Path('renders/fix-crops').glob('*.jpg')),*sorted(Path('renders/round4-crops').glob('*.jpg')),Path('renders/final/contact.jpg')]
  for folder in ('renders/final-matches','renders/final-source-matches'):
   products.extend(sorted(Path(folder).glob('*.jpg')))
  before={str(p):sha(p) for p in products}
  sys.path.insert(0,str(ROOT))
  from kit.photo_match import compose
  for folder in ('renders/final-matches','renders/final-source-matches'):compose('build/cameras.json',folder,folder)
  run([sys.executable,str(HERE/'final_evidence.py')],ASSET,target/'evidence.log')
  run([sys.executable,str(HERE/'round4_evidence.py')],ASSET,target/'round4-evidence.log')
  run([sys.executable,str(HERE/'docs.py')],ASSET,target/'docs.log')
  presentation=[dict(file=p,sha256=h,bytes=Path(p).stat().st_size,identical=sha(p)==h) for p,h in before.items()]
  assert all(r['identical'] for r in presentation),('CPU presentation repeat',presentation)
 report['presentation_files']=presentation;report['scope']+=' CPU photo/crop/contact/gallery assembly also repeats exactly from the same rendered inputs when finals exist.'
 Path('build/repeat.json').write_text(json.dumps(report,indent=2))
 print('REPEAT PASSED',len(rows)+len(geometry)+len(presentation),'deterministic files byte-identical')
if __name__=='__main__':main()
