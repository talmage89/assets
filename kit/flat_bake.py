"""Bake an original periodic raster/height material on a physical flat tile.

Inputs are generated by the family's own scripts, never reference photographs.
BaseColor and ORM emission bakes are lighting independent. Cycles tangent
normal bake evaluates the meter-valued height with a physical UV footprint.
"""
import argparse, sys, json
from pathlib import Path
import bpy
import numpy as np
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from kit import gpu
from kit.image_io import write_png


def bake(source, out, name, coverage, size, samples):
    bpy.ops.wm.read_factory_settings(use_empty=True)
    sc = bpy.context.scene; sc.render.engine = 'CYCLES'; sc.cycles.samples = samples
    gpu.enable(); sc.render.bake.margin = 0
    bpy.ops.mesh.primitive_plane_add(size=coverage)
    ob = bpy.context.object
    mat = bpy.data.materials.new(name); mat.use_nodes = True; ob.data.materials.append(mat)
    nodes, links = mat.node_tree.nodes, mat.node_tree.links; nodes.clear()
    output = nodes.new('ShaderNodeOutputMaterial')
    target = nodes.new('ShaderNodeTexImage')
    report = {}
    for channel in ('BaseColor', 'ORM', 'Normal'):
        for link in list(links): links.remove(link)
        image = bpy.data.images.new('Bake '+channel, width=size, height=size, float_buffer=True)
        image.colorspace_settings.name = 'Non-Color'
        target.image = image; nodes.active = target; target.select = True
        src = nodes.new('ShaderNodeTexImage')
        src.image = bpy.data.images.load(str((source / f'T_{name}_{"Height" if channel=="Normal" else channel}.png').resolve()))
        src.image.colorspace_settings.name = 'sRGB' if channel == 'BaseColor' else 'Non-Color'
        src.extension = 'REPEAT'; src.interpolation = 'Linear'
        if channel == 'Normal':
            shader = nodes.new('ShaderNodeBsdfPrincipled'); bump = nodes.new('ShaderNodeBump')
            bump.inputs['Distance'].default_value = .004
            links.new(src.outputs['Color'], bump.inputs['Height']); links.new(bump.outputs['Normal'], shader.inputs['Normal'])
            links.new(shader.outputs[0], output.inputs['Surface'])
            bpy.ops.object.bake(type='NORMAL', normal_space='TANGENT', normal_r='POS_X', normal_g='POS_Y', normal_b='POS_Z')
        else:
            shader = nodes.new('ShaderNodeEmission'); links.new(src.outputs['Color'], shader.inputs['Color'])
            links.new(shader.outputs[0], output.inputs['Surface']); bpy.ops.object.bake(type='EMIT')
        array = np.empty(size*size*4, np.float32); image.pixels.foreach_get(array)
        array = array.reshape(size, size, 4)[::-1, :, :3]
        if channel == 'BaseColor':
            from kit.image_io import linear_to_srgb
            array = linear_to_srgb(array)
        path = out / f'T_{name}_{channel}.png'; write_png(path, array, bits=16 if channel=='Normal' else 8)
        report[channel] = dict(bytes=path.stat().st_size, size=size)
        if channel == 'BaseColor':
            from PIL import Image
            original = np.asarray(Image.open(source / f'T_{name}_BaseColor.png')).astype(np.float32) / 255
            error = np.abs(array - original[:, :, :3])
            bias = float(np.max(np.abs(array.mean(axis=(0,1),dtype=np.float64)-original[:, :, :3].mean(axis=(0,1),dtype=np.float64))))
            report[channel].update(source_max_error=float(error.max()), source_mean_error=float(error.mean()), source_mean_bias=bias)
            # Bake AA resamples texel footprints. A color-space error changes the
            # whole mean, whereas grain filtering changes individual pixels.
            if bias > .005 or float(error.mean()) > .02:
                raise AssertionError(f'Color-space or UV bake mismatch: mean bias {bias}')
        nodes.remove(src); nodes.remove(shader); bpy.data.images.remove(image)
    out.mkdir(parents=True, exist_ok=True)
    (out / f'{name}-bake.json').write_text(json.dumps(dict(coverage_m=coverage, samples=samples, channels=report), indent=2))


if __name__ == '__main__':
    p = argparse.ArgumentParser(); p.add_argument('--source', type=Path, required=True); p.add_argument('--out', type=Path, required=True)
    p.add_argument('--name', required=True); p.add_argument('--coverage', type=float, required=True)
    p.add_argument('--size', type=int, default=4096); p.add_argument('--samples', type=int, default=8)
    a = p.parse_args(sys.argv[sys.argv.index('--')+1:]); bake(a.source, a.out, a.name, a.coverage, a.size, a.samples)
