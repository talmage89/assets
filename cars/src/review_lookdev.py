"""Source review JPGs, complete contact sheets and masked tonal measurements."""
import argparse,hashlib,json,math
from pathlib import Path
import numpy as np
from PIL import Image,ImageDraw,ImageFont
import sys
sys.path.insert(0,str(Path(__file__).resolve().parents[2]))
from kit.fonts import find_font
FONT=find_font('Noto Sans', 'Regular')

def panel(path,size):
    im=Image.open(path).convert('RGBA');im.thumbnail(size,Image.Resampling.LANCZOS)
    tile=Image.new('RGB',size,(226,228,225));tile.paste(im,((size[0]-im.width)//2,(size[1]-im.height)//2),im.getchannel('A'));return tile

def sheet(files,out,columns=3,width=560):
    h=385;canvas=Image.new('RGB',(columns*width,math.ceil(len(files)/columns)*h),(226,228,225));d=ImageDraw.Draw(canvas);font=ImageFont.truetype(FONT,17)
    for i,path in enumerate(files):
        x=i%columns*width;y=i//columns*h
        canvas.paste(panel(path,(width,h-38)),(x,y+38));d.text((x+14,y+8),path.stem,font=font,fill=(25,32,30))
    canvas.save(out,quality=92,optimize=True)

def main():
    p=argparse.ArgumentParser();p.add_argument('--renders',required=True);a=p.parse_args();root=Path(a.renders)
    metadata=json.loads((root/'shots.json').read_text());files=[];tonal={}
    if len({s['source_sha256'] for s in metadata.values()})!=1:raise AssertionError('Mixed source revisions in review directory')
    if len({s['render_recipe_sha256'] for s in metadata.values()})!=1:raise AssertionError('Mixed render recipes in review directory')
    source=Path(next(iter(metadata.values()))['source'])
    if hashlib.sha256(source.read_bytes()).hexdigest()!=next(iter(metadata.values()))['source_sha256']:raise AssertionError('Renders predate current source')
    for name,shot in metadata.items():
        path=root/(name+'.png')
        if not path.exists():continue
        files.append(path);im=Image.open(path).convert('RGBA');rgb=np.asarray(im)[...,:3].astype(float)/255
        mask=np.asarray(Image.open(root/shot['tonal_mask']).convert('RGBA'));valid=mask[...,3]>200
        paint=valid&(mask[...,:3].mean(axis=2)>240)
        luma=rgb@np.array([.2126,.7152,.0722]);measure={}
        for label,selection in [('vehicle',valid),('paint',paint)]:
            v=luma[selection];cols=rgb[selection]
            measure[label]=dict(pixel_count=int(len(v)),display_luma_percentiles={str(p):float(np.percentile(v,p)) for p in [1,5,50,95,99]},
                any_channel_255_fraction=float(np.mean(cols.max(axis=1)>=1)),
                any_channel_ge_254_fraction=float(np.mean(cols.max(axis=1)>=254/255)),
                all_channels_ge_250_fraction=float(np.mean(cols.min(axis=1)>=250/255)),
                deep_shadow_below_25_fraction=float(np.mean(v<25/255)))
        tonal[name]=dict(source_sha256=shot['source_sha256'],paint=shot['paint'],engine=shot['engine'],measurements=measure)
        # JPEG conversion only; never used as texture input.
        jpg=Image.new('RGB',im.size,(226,228,225));jpg.paste(im,mask=im.getchannel('A'));jpg.save(root/(name+'.jpg'),quality=94,optimize=True)
    (root/'tonal-range.json').write_text(json.dumps(dict(method='display-referred sRGB luminance, opaque-geometry and paint-only Workbench masks; floor excluded; no albedo inferred from lit pixels',shots=tonal),indent=2))
    sheet(files,root/'contact.jpg')
    colors=[p for p in files if p.stem.startswith('paint_')]
    if colors:sheet(colors,root/'five-colors.jpg')
    pairs=sorted(root.glob('*-pair.jpg'))
    if pairs:sheet(pairs,root/'used-pairs-contact.jpg',columns=1,width=1600)
    # Open this once to inspect every diagnostic mask generated by the renderer.
    sheet([root/(n+'-mask.png') for n in metadata if (root/(n+'-mask.png')).exists()],root/'mask-contact.jpg')
    print('SOURCE_REVIEW',len(files),'rendered views; tonal-range.json; contact.jpg; masks inspected separately')
if __name__=='__main__':main()
